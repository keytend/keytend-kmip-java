/**
 * The persisted formats stay readable. Each fixture under {@code
 * formats/<version>/} is what that version wrote ({@link FormatFixtures}, compiled against the
 * release's JAR), and this version must still open it: a {@code Ciphertext} (KTC 1) of AES-GCM,
 * AES-CBC and AES key wrap, a sealed record (KTE 1), a sealed stream (KTS 1) and a chunked file
 * (KTR 1: a header and three chunks, {@link ChunkedFormatFixtures}), through KMIP 1.4, 2.1 and the
 * 3.0 draft. The fixtures' hashes are pinned, so a fixture is never regenerated by accident: a
 * release's fixtures are added, never replaced (docs/compatibility.md).
 *
 * <p>keytend-kmip's formats start at its first release, 0.10.0, whose set, {@code formats/0.10.0/},
 * pins what the tree writes, so a change to a format fails here. Every later release adds its own
 * set by the time it becomes the API baseline.
 */
class PersistedFormatsTest {
  /** Every fixture of every version, and its SHA-256. */
  static final Map<String, String> PINNED =
      Map.ofEntries(
          Map.entry(
              "0.10.0/ktc-aes-cbc.bin",
              "6aa78cdebe8b5ddc1223c1a69388e75f990b0d5434451db5a2be37e00d96d8ac"),
          Map.entry(
              "0.10.0/ktc-aes-gcm.bin",
              "5c485cc0f749d44e329b934806522da6721d2f5ef9e65e8a562e3097a67f3e27"),
          Map.entry(
              "0.10.0/ktc-aes-kw.bin",
              "68ac8a845d34b3b0987b651b5b59b41e036657cb23bf90569142ab0b13e82776"),
          Map.entry(
              "0.10.0/kte.bin", "d8b4d6144c7daedb45f52886d1e3cb747b89696d3c53440dc0ddb288412d7a8d"),
          Map.entry(
              "0.10.0/ktr-chunk-0.bin",
              "0e8baafec90ea7b8f86682b805a3e35e760ca759b68103820a69184beb8ed8ab"),
          Map.entry(
              "0.10.0/ktr-chunk-1.bin",
              "ae857741c1b65cb0579cf9a2eea5b88bab0821c8c8be4d49d293cb66dfe550d8"),
          Map.entry(
              "0.10.0/ktr-chunk-2.bin",
              "03f54c12b795ff5f8e3649f8e97902bf425cc45aab3f365ae8f22a1fcc21c7a2"),
          Map.entry(
              "0.10.0/ktr-header.bin",
              "73d2b605961d20e91ddbeca7800d18ad1a58f5e914aab99570b2ab733dd43682"),
          Map.entry(
              "0.10.0/kts.bin",
              "104fbd9c23fed64e51c557a654f3b6d4e7e0393d02b248517c74a76532f8af08"));

  /**
   * The fixture sets here: releases from 0.10.0, each added at the latest when it becomes the API
   * baseline (docs/releasing.md).
   */
  static final List<String> WRITTEN = List.of("0.10.0");

  static Stream<Arguments> cases() {
    List<Arguments> out = new ArrayList<>();
    for (String written : WRITTEN)
      for (KmipVersion version : List.of(KmipVersion.V1_4, KmipVersion.V2_1, KmipVersion.V3_0))
        out.add(Arguments.of(written, version));
    return out.stream();
  }

  /** The sets with KTR fixtures: all of them. */
  static Stream<Arguments> chunkedCases() {
    return cases();
  }

  static byte[] fixture(String path) throws IOException {
    try (InputStream in = PersistedFormatsTest.class.getResourceAsStream("/formats/" + path)) {
      assertNotNull(in, "the fixture " + path);
      byte[] b = in.readAllBytes();
      assertEquals(
          PINNED.get(path), sha256(b), "the pinned fixture " + path + ": never regenerate one");
      return b;
    }
  }

  static String sha256(byte[] b) {
    try {
      return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(b));
    } catch (java.security.NoSuchAlgorithmException e) {
      throw new AssertionError(e);
    }
  }

  @ParameterizedTest(name = "written by {0}, opened at KMIP {1}")
  @MethodSource("cases")
  void everyPersistedFormatStillOpens(String written, KmipVersion version) throws IOException {
    InMemoryKmipServer server = FormatFixtures.server(version);
    try (Kms kms = server.connect()) {
      KeyHandle kek = kms.keys().handle(KEK_ID);

      // KTC 1: the header is the stored key identifier and spec name, and a round trip keeps the
      // bytes.
      Map<String, String> specs =
          Map.of(
              "ktc-aes-gcm.bin",
              "AES-GCM-16",
              "ktc-aes-cbc.bin",
              "AES-CBC",
              "ktc-aes-kw.bin",
              "AES-KW");
      for (Map.Entry<String, String> e : specs.entrySet()) {
        byte[] bytes = fixture(written + "/" + e.getKey());
        assertArrayEquals("KTC".getBytes(StandardCharsets.US_ASCII), Arrays.copyOf(bytes, 3));
        assertEquals(1, bytes[3], "format version 1");
        Ciphertext c = Ciphertext.fromBytes(bytes);
        assertEquals(KEK_ID, c.keyId());
        assertEquals(e.getValue(), c.specName());
        assertArrayEquals(bytes, c.toBytes());
      }
      assertArrayEquals(
          plaintext(100),
          kek.decrypt(Ciphertext.fromBytes(fixture(written + "/ktc-aes-gcm.bin")), AAD));
      assertArrayEquals(
          plaintext(48),
          kek.decrypt(
              CipherSpec.cbc(), Ciphertext.fromBytes(fixture(written + "/ktc-aes-cbc.bin")), null));
      DestroyableSecretKey unwrapped =
          kek.unwrapKey(
              Expect.aes(256), Ciphertext.fromBytes(fixture(written + "/ktc-aes-kw.bin")), null);
      assertArrayEquals(FormatFixtures.wrappedKeyBytes(), unwrapped.getEncoded());
      unwrapped.destroy();

      // KTE 1.
      byte[] kte = fixture(written + "/kte.bin");
      assertArrayEquals("KTE".getBytes(StandardCharsets.US_ASCII), Arrays.copyOf(kte, 3));
      assertEquals(1, kte[3]);
      assertEquals(KEK_ID, KmsKeys.sealedKeyId(kte));
      assertArrayEquals(plaintext(1000), kek.open(kte, AAD));

      // KTS 1, and not vacuously: one byte short does not open.
      byte[] kts = fixture(written + "/kts.bin");
      assertArrayEquals("KTS".getBytes(StandardCharsets.US_ASCII), Arrays.copyOf(kts, 3));
      assertEquals(1, kts[3]);
      assertEquals(KEK_ID, KmsKeys.sealedStreamKeyId(new ByteArrayInputStream(kts)));
      try (InputStream in = kek.opening(new ByteArrayInputStream(kts), AAD)) {
        assertArrayEquals(plaintext(FormatFixtures.STREAM_SIZE), in.readAllBytes());
      }
      byte[] cut = Arrays.copyOf(kts, kts.length - 1);
      assertThrows(
          CryptographicFailureException.class,
          () -> {
            try (InputStream in = kek.opening(new ByteArrayInputStream(cut), AAD)) {
              in.readAllBytes();
            }
          });
      // Changed additional data: the fixtures are bound to it.
      assertThrows(
          CryptographicFailureException.class,
          () -> kek.open(kte, "other".getBytes(StandardCharsets.UTF_8)));

      // This version still writes the same headers.
      Ciphertext now = kek.encrypt(CipherSpec.aesGcm(), plaintext(100), AAD);
      assertArrayEquals(
          Ciphertext.fromBytes(fixture(written + "/ktc-aes-gcm.bin")).header(), now.header());
      assertEquals(List.of(), server.violations());
    } finally {
      server.close();
    }
  }

  /**
   * KTR 1: the header names the KEK, and every chunk opens by its index, through the KEK's handle
   * and through a query, the last one as the final chunk; not vacuously: a chunk at another index,
   * a cut chunk and another file identifier fail. This version writes the same layout.
   */
  @ParameterizedTest(name = "written by {0}, opened at KMIP {1}")
  @MethodSource("chunkedCases")
  void theChunkedFormatStillOpens(String written, KmipVersion version) throws IOException {
    InMemoryKmipServer server = FormatFixtures.server(version);
    try (Kms kms = server.connect()) {
      KeyHandle kek = kms.keys().handle(KEK_ID);
      byte[] header = fixture(written + "/ktr-header.bin");
      assertArrayEquals("KTR".getBytes(StandardCharsets.US_ASCII), Arrays.copyOf(header, 3));
      assertEquals(1, header[3], "format version 1");
      assertEquals(KEK_ID, KmsKeys.chunkedHeaderKeyId(header));
      byte[][] chunks = new byte[ChunkedFormatFixtures.CHUNKS][];
      for (int i = 0; i < chunks.length; i++)
        chunks[i] = fixture(written + "/ktr-chunk-" + i + ".bin");
      int last = chunks.length - 1;
      for (ChunkedOpener o :
          List.of(
              kek.chunkedOpener(header, ChunkedFormatFixtures.fileId()),
              kms.keys()
                  .chunkedOpener(
                      KeyQuery.all().algorithm(Algorithm.AES),
                      header,
                      ChunkedFormatFixtures.fileId()))) {
        try (o) {
          for (int i : new int[] {2, 0, 1})
            assertArrayEquals(ChunkedFormatFixtures.chunk(i), o.open(i, chunks[i]), "chunk " + i);
          assertArrayEquals(ChunkedFormatFixtures.chunk(last), o.openFinal(last, chunks[last]));
          assertThrows(
              CryptographicFailureException.class,
              () -> o.openFinal(1, chunks[1]),
              "chunk 1 is not the final chunk");
          assertThrows(
              CryptographicFailureException.class,
              () -> o.open(1, chunks[0]),
              "chunk 0 at index 1");
          assertThrows(
              CryptographicFailureException.class,
              () -> o.open(0, Arrays.copyOf(chunks[0], chunks[0].length - 1)));
        }
      }
      assertThrows(
          CryptographicFailureException.class,
          () -> kek.chunkedOpener(header, "other".getBytes(StandardCharsets.UTF_8)));

      // This version still writes the same layout: the magic and version, a core of 44 bytes, and
      // a wrapped key of the same length under the same key.
      try (ChunkedSealer now = kek.chunkedSealer(ChunkedFormatFixtures.fileId())) {
        byte[] h = now.header();
        assertArrayEquals(Arrays.copyOf(header, 4), Arrays.copyOf(h, 4));
        assertEquals(header.length, h.length);
        assertArrayEquals(Arrays.copyOfRange(header, 44, 46), Arrays.copyOfRange(h, 44, 46));
        assertEquals(chunks[0].length, now.seal(0, ChunkedFormatFixtures.chunk(0)).length);
      }
      assertEquals(List.of(), server.violations());
    } finally {
      server.close();
    }
  }

  /**
   * The release {@code sdk/pom.xml} pins as the API baseline has its fixtures here, so moving the
   * baseline to one without adding them fails. While none is pinned (the tree builds the first
   * release, 0.10.0, or one of its pre-releases: tools/api-baseline.sh), that release's set is
   * required. Every fixture directory is one this test opens and pins.
   */
  @Test
  void theApiBaselineReleaseHasPinnedFixtures() throws IOException {
    String pom = Files.readString(Path.of("pom.xml"));
    String name = pinned(pom, "name"), baseline = pinned(pom, "version");
    Path formats = Path.of("src/test/resources/formats");
    String required;
    if (name == null && baseline == null) {
      Matcher building =
          Pattern.compile(
                  "<artifactId>keytend-kmip-parent</artifactId>\\s*<version>([^<]+)</version>")
              .matcher(Files.readString(Path.of("../pom.xml")));
      assertTrue(building.find(), "the project version in pom.xml");
      required = building.group(1).strip().replaceFirst("-rc\\.\\d+$", "");
    } else {
      assertEquals("keytend-kmip", name, "sdk/pom.xml pins a keytend-kmip release");
      assertNotNull(baseline, "sdk/pom.xml pins api.baseline.version");
      required = baseline;
    }
    assertTrue(
        Files.isDirectory(formats.resolve(required)),
        "no stored-format fixtures for "
            + required
            + ": add formats/"
            + required
            + "/ (docs/releasing.md)");
    assertTrue(WRITTEN.contains(required), "the release's fixtures are opened: " + required);
    List<String> dirs;
    try (Stream<Path> list = Files.list(formats)) {
      dirs = list.filter(Files::isDirectory).map(d -> d.getFileName().toString()).sorted().toList();
    }
    assertEquals(new TreeSet<>(WRITTEN), new TreeSet<>(dirs), "every fixture directory is opened");
    for (String v : WRITTEN)
      try (Stream<Path> files = Files.list(formats.resolve(v))) {
        for (Path f : files.toList())
          assertTrue(
              PINNED.containsKey(v + "/" + f.getFileName()),
              "pinned: " + v + "/" + f.getFileName());
      }
  }

  /** The {@code api.baseline.<property>} that {@code pom} pins, or null when it pins none. */
  static String pinned(String pom, String property) {
    Matcher m =
        Pattern.compile(
                "<api\\.baseline\\." + property + ">([^<]*)</api\\.baseline\\." + property + ">")
            .matcher(pom);
    return m.find() ? m.group(1).strip() : null;
  }
}
